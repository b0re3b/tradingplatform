class StrategyTradeTier(StrEnum):
    """
    Strategy-side suggested trade tier.

    Mirrors risk TradeTier values. Strategy may suggest a tier, but RiskManager
    may downgrade or reject it.
    """

    T1 = "t1"
    T2 = "t2"
    T3 = "t3"
    T4 = "t4"

    @property
    def rank(self) -> int:
        return {
            StrategyTradeTier.T1: 1,
            StrategyTradeTier.T2: 2,
            StrategyTradeTier.T3: 3,
            StrategyTradeTier.T4: 4,
        }[self]

    @classmethod
    def from_rank(cls, rank: int) -> "StrategyTradeTier":
        normalized = max(1, min(int(rank), 4))
        return {
            1: cls.T1,
            2: cls.T2,
            3: cls.T3,
            4: cls.T4,
        }[normalized]

    def downgrade(self, steps: int = 1) -> "StrategyTradeTier":
        return self.from_rank(self.rank - max(0, int(steps)))


