class StrEnum(str, Enum):
    """
    Base enum that behaves as a stable lowercase string.

    Strategy package deliberately keeps its own enums instead of importing
    risk.enums directly. Cross-package conversion should happen only at the
    EventBus boundary when SignalProcessor/SignalRouter builds signal.generated
    payload for RiskManager.
    """

    def __str__(self) -> str:
        return self.value

    @classmethod
    def values(cls) -> tuple[str, ...]:
        return tuple(item.value for item in cls)

    @classmethod
    def has_value(cls, value: str) -> bool:
        return value in cls.values()

    @classmethod
    def safe_parse(cls, value: object, default: "StrEnum") -> "StrEnum":
        if isinstance(value, cls):
            return value
        if isinstance(value, str):
            try:
                return cls(value)
            except ValueError:
                return default
        return default


class SignalSide(StrEnum):
    """
    Strategy-side signal direction.

    Maps to risk PositionSide only when creating the signal.generated payload.
    FLAT/UNKNOWN must never be sent to RiskManager as an opening trade.
    """

    LONG = "long"
    SHORT = "short"
    FLAT = "flat"
    UNKNOWN = "unknown"

    @property
    def is_directional(self) -> bool:
        return self in {SignalSide.LONG, SignalSide.SHORT}

    @property
    def sign(self) -> int:
        if self is SignalSide.LONG:
            return 1
        if self is SignalSide.SHORT:
            return -1
        return 0


class SignalStatus(StrEnum):
    """
    Runtime lifecycle status of strategy signals.

    Risk/execution responses should update this state through StrategyEventHandler
    and SignalState, not by direct calls from risk/execution packages.
    """

    NEW = "new"
    PENDING = "pending"
    CONFIRMED = "confirmed"
    REJECTED = "rejected"
    CANCELLED = "cancelled"
    EXPIRED = "expired"
    EXECUTED = "executed"
    FAILED = "failed"

    @property
    def is_active(self) -> bool:
        return self in {
            SignalStatus.NEW,
            SignalStatus.PENDING,
            SignalStatus.CONFIRMED,
        }

    @property
    def is_terminal(self) -> bool:
        return self in {
            SignalStatus.REJECTED,
            SignalStatus.CANCELLED,
            SignalStatus.EXPIRED,
            SignalStatus.EXECUTED,
            SignalStatus.FAILED,
        }


